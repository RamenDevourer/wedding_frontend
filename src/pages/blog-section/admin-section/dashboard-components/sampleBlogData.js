// Get recent blogs (last 7)
export const getRecentBlogs = () => {
  return [...sampleBlogs]
    .sort((a, b) => new Date(b.updatedAt) - new Date(a.updatedAt))
    .slice(0, 7);
};

// Get blog counts
export const getBlogCounts = () => {
  const total = sampleBlogs.length;
  const published = sampleBlogs.filter(blog => blog.status === 'published').length;
  const draft = sampleBlogs.filter(blog => blog.status === 'draft').length;
  
  return { total, published, draft };
};
